ID_OK = re.compile(r'^[a-z][a-z0-9]*(-[a-z0-9]+)*$')


def die(msg):
    print('[gen] ERROR: ' + msg, file=sys.stderr)
    sys.exit(1)


def check(oid, title, lines):
    if not ID_OK.match(oid):
        die('id 规范错误：%r' % oid)
    for i, l in enumerate(lines):
        if re.search(r'[A-Za-z]', l):
            die('%s 第%d句混入拉丁字母：%r' % (title, i + 1, l))
        if re.search(r'[�□]', l):
            die('%s 第%d句含乱码字符：%r' % (title, i + 1, l))


def main():
    dry = '--dry' in sys.argv
    ids = [d[0] for d in DATA]
    dup = {x for x in ids if ids.count(x) > 1}
    if dup:
        die('id 重复：%s' % dup)
    for d in DATA:
        check(d[0], d[1], d[5])       # d[5] 是 lines

    if dry:
        print('[gen] --dry：%d 篇待生成' % len(DATA))
        return

    written = 0
    for (oid, title, author, dyn, volume, lines, theme, emo, tech,
         recite, now) in DATA:
        n = len(lines)
        pairs = ['%d-%d' % (i, i + 1) for i in range(0, n - 1, 2)]
        split = [max(1, len([x for x in l.rstrip('。！？；').split('，') if x.strip()]))
                 for l in lines]

        fm = [
            '---',
            'id: %s' % oid,
            'title: %s' % title,
            'subtitle: null',
            'author: %s' % author,
            'dynasty: %s' % dyn,
            'form: 文言',
            'stage: 高中',
            'grade: null',
            'volume: %s' % volume,
            'textbooks: [统编]',
            'recite: %s' % recite,
            'syllabus: {gaokao2017: true, gaokaoNow: %s}' % ('true' if now else 'false'),
            'theme: [%s]' % ', '.join(theme),
            'emotion: %s' % emo,
            'technique: [%s]' % ', '.join(tech),
            'difficulty: %d' % (5 if n >= 4 else 4),
            'exam_freq: %s' % (0.8 if now else 0.9),
            'pairs: [%s]' % ', '.join(pairs),
            'tags: [%s]' % ', '.join(theme + [dyn + '文言']),
            'source: S3+S1b+S2',
            'license: public-domain',
            'copyright: { text: public-domain, annotations: cc-by-4.0 }',
            '---',
            '',
        ]
        if any(x != 1 for x in split):
            fm.insert(-2, 'render_split: [%s]' % ', '.join(str(x) for x in split))

        body = [
            '# %s' % title, '',
            '> %s · %s · 文言 · 高中 · %s' % (author, dyn, volume), '',
            '## 必背名句', '',
        ]
        for l in lines:
            body.append(l)
            body.append('')
        body += [
            '## 全文',
            '',
            '> 完整原文待补（不影响游戏：游戏只用上面的必背名句）',
            '',
            '## 注释', '', '- （待补：字词注释）', '',
            '## 译文', '', '（待补：白话译文）', '',
            '## 赏析', '', '（待补：文学常识与赏析）', '',
        ]

        out = POEMS_DIR / volume / ('%s.md' % title)
        if out.exists():
            print('  ! 跳过（已存在）%s' % out.relative_to(ROOT))
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text('\n'.join(fm + body), encoding='utf-8')
        written += 1
        print('  ✓ %-16s %s' % (volume, title))

    print('[gen] 写出 %d 篇' % written)


if __name__ == '__main__':
    main()